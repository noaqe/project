-- Run only in a database allocated to this application.
-- CREATE TABLE IF NOT EXISTS makes repeated initialization non-destructive;
-- this is an initial schema, not a general migration system.
CREATE SCHEMA IF NOT EXISTS library;
SET search_path TO library;

CREATE TABLE IF NOT EXISTS authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn VARCHAR(13) NOT NULL UNIQUE CHECK (isbn ~ '^[0-9]{13}$'),
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    publication_year INTEGER NOT NULL CHECK (publication_year BETWEEN 1450 AND 2100),
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    total_copies INTEGER NOT NULL CHECK (total_copies BETWEEN 1 AND 10000)
);

CREATE TABLE IF NOT EXISTS book_authors (
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES authors(id) ON DELETE RESTRICT,
    PRIMARY KEY (book_id, author_id)
);

CREATE TABLE IF NOT EXISTS readers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(160) NOT NULL UNIQUE CHECK (email = lower(email) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    membership_type VARCHAR(10) NOT NULL CHECK (membership_type IN ('STUDENT', 'GUEST'))
);

CREATE TABLE IF NOT EXISTS loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    reader_id BIGINT NOT NULL REFERENCES readers(id) ON DELETE RESTRICT,
    borrowed_on DATE NOT NULL,
    due_on DATE NOT NULL,
    returned_on DATE,
    CHECK (due_on >= borrowed_on),
    CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_active_reader_book
    ON loans(reader_id, book_id) WHERE returned_on IS NULL;
CREATE INDEX IF NOT EXISTS idx_books_category ON books(category_id);
CREATE INDEX IF NOT EXISTS idx_book_authors_author ON book_authors(author_id);
CREATE INDEX IF NOT EXISTS idx_loans_book ON loans(book_id);
CREATE INDEX IF NOT EXISTS idx_loans_reader ON loans(reader_id);
CREATE INDEX IF NOT EXISTS idx_active_loans_due ON loans(due_on) WHERE returned_on IS NULL;
